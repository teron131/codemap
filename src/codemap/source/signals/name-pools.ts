/** Checks whether a name-pool row is useful project vocabulary. */
export function isUsefulNamePoolTerm(name: string): boolean {
	const trimmed = name.trim();
	const normalized = trimmed.toLowerCase();
	if (trimmed.startsWith("_")) {
		return false;
	}
	if (/^[A-Z0-9_]+$/.test(trimmed) && /[A-Z]/.test(trimmed)) {
		return false;
	}
	if (/^[A-Z]/.test(trimmed) && /(Error|Exception)$/.test(trimmed)) {
		return false;
	}
	return normalized.length > 1 && !NOISY_NAME_POOL_TERMS.has(normalized);
}
